import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const manifest = JSON.parse(readFileSync('.agents/manifest.json', 'utf8'));
const check = process.argv.includes('--check');
let stale = false;
for (const role of manifest.roles) {
  const instruction = `Read AGENTS.md and .agents/WORKFLOW.md, then ${role.profile}. Apply that canonical specialist profile to the assigned task. Return actual evidence, findings and limitations. Do not claim independent review if you are the implementer. Do not change code during a review assignment unless explicitly tasked. Inherit runtime model and permissions; this profile grants no additional access.`;
  const files = [
    [
      `.codex/agents/${role.id}.toml`,
      `# Generated by pnpm agents:sync; edit canonical profiles instead.\nname = ${JSON.stringify(role.id.replaceAll('-', '_'))}\ndescription = ${JSON.stringify(role.description)}\ndeveloper_instructions = ${JSON.stringify(instruction)}\n`,
    ],
    [
      `.claude/agents/${role.id}.md`,
      `---\nname: ${role.id}\ndescription: ${JSON.stringify(role.description)}\n---\n\n<!-- Generated by pnpm agents:sync. -->\n\n${instruction}\n`,
    ],
  ];
  for (const [path, expected] of files) {
    if (check) {
      let actual;
      try {
        actual = readFileSync(path, 'utf8');
      } catch {
        actual = '';
      }
      if (actual !== expected) {
        console.error(`Stale or missing adapter: ${path}`);
        stale = true;
      }
    } else {
      mkdirSync(path.slice(0, path.lastIndexOf('/')), { recursive: true });
      writeFileSync(path, expected);
    }
  }
}
if (stale) process.exitCode = 1;
else
  console.info(
    check
      ? 'Agent adapters match the canonical catalog.'
      : 'Agent adapters generated.',
  );
